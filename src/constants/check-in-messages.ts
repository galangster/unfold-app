/**
 * Select a message deterministically based on day of year.
 * Same message each day, cycles yearly.
 */
export function getMessageForToday(messages: string[]): string {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - start.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  return messages[dayOfYear % messages.length];
}

